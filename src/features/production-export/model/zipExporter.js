import {
  createZipBlob,
  sanitizeFilename,
  sanitizeIdentifier,
} from "../../../shared/lib/index.js";
import { FORMAT_META, generateDeveloperCode } from "./codeGenerators.js";
import { generateExportSvg } from "./svgExporter.js";

/**
 * Builds deduplicated Batch ZIP entries respecting active transforms, rootAttrs, and exportTarget.
 */
function buildBatchZipEntries(state) {
  const W = state.width;
  const H = state.height;
  const format = FORMAT_META[state.exportCodeFormat]
    ? state.exportCodeFormat
    : "figma";
  const folderPrefix = `icons_${W}x${H}`;
  const entries = [];
  const usedFiles = new Map();
  const usedExports = new Map();

  let indexTsContent = `// Generated by Icon Studio (${W}x${H})

`;

  const batchState = {
    ...state,
    exportTarget:
      state.exportTarget === "guides" ? "clean" : state.exportTarget,
  };

  const selectedIds = state.selectedCompareIndices;
  const targetIcons =
    selectedIds && selectedIds.size >= 2
      ? state.batchQueue.filter((_, idx) => selectedIds.has(idx))
      : state.batchQueue;

  targetIcons.forEach((icon, idx) => {
    const rawBase = sanitizeFilename(icon.name) || `icon_${idx + 1}`;
    const fileCount = (usedFiles.get(rawBase) || 0) + 1;
    usedFiles.set(rawBase, fileCount);
    const uniqueBase = fileCount > 1 ? `${rawBase}_${fileCount}` : rawBase;

    const baseComp = sanitizeIdentifier(uniqueBase, "Icon");
    const compCount = (usedExports.get(baseComp) || 0) + 1;
    usedExports.set(baseComp, compCount);
    const uniqueComp = compCount > 1 ? `${baseComp}_${compCount}` : baseComp;

    if (format === "react") {
      const fileName = `${uniqueComp}.jsx`;
      const content = generateDeveloperCode(batchState, "react", icon);
      entries.push({ path: `${folderPrefix}/${fileName}`, content });
      indexTsContent += `export { ${uniqueComp} } from './${uniqueComp}';
`;
    } else if (format === "androidXml") {
      const fileName = `ic_${uniqueBase.toLowerCase()}_${W}dp.xml`;
      const content = generateDeveloperCode(batchState, "androidXml", icon);
      entries.push({ path: `${folderPrefix}/${fileName}`, content });
    } else {
      const fileName = `${uniqueBase}_${W}px.svg`;
      const content = generateExportSvg(batchState, icon);
      entries.push({ path: `${folderPrefix}/${fileName}`, content });
      indexTsContent += `export { default as ${uniqueComp} } from './${fileName}';
`;
    }
  });

  if (format !== "androidXml") {
    entries.push({ path: `${folderPrefix}/index.ts`, content: indexTsContent });
  }

  const suffix = format === "figma" ? "v1.0" : FORMAT_META[format].ext;
  return {
    archiveName: `icon_pack_${W}x${H}_${suffix}.zip`,
    entries,
  };
}

export function createBatchZipPackage(state) {
  const { archiveName, entries } = buildBatchZipEntries(state);
  const selectedCount = state.selectedCompareIndices?.size || 0;
  return {
    archiveName,
    blob: createZipBlob(entries),
    count: selectedCount >= 2 ? selectedCount : state.batchQueue.length,
  };
}
